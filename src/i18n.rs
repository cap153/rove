/// 把设置里的语言选项解析成实际使用的字典。
fn is_zh(language: &str) -> bool {
    match language {
        "zh-CN" => true,
        "en" => false,
        _ => system_is_chinese(), // 跟随系统
    }
}

pub fn strings_for(language: &str) -> Vec<SharedString> {
    let src = if is_zh(language) { ZH } else { EN };
    src.iter().map(|s| SharedString::from(*s)).collect()
}

/// Rust 侧也按同一份字典取文案：设置页标题/导航等由代码生成的文本，
/// 必须与 Slint 里 I18n.strings 的取值一致（设置页用标题比较切子页）。
/// 供 Rust 侧按语言分支拼装带数字的句子。
pub fn is_chinese(language: &str) -> bool { is_zh(language) }

pub fn text(language: &str, zh_key: &str) -> SharedString {
    match ZH.iter().position(|s| *s == zh_key) {
        Some(i) => SharedString::from((if is_zh(language) { ZH } else { EN })[i]),
        None => SharedString::from(zh_key),
    }
}

pub fn apply(ui: &MainWindow, language: &str) {
    let values = strings_for(language);
    ui.global::<I18n>()
        .set_strings(ModelRc::new(VecModel::from(values)));
}

#[cfg(windows)]
fn system_is_chinese() -> bool {
    use std::sync::OnceLock;
    use windows_sys::Win32::Globalization::GetUserDefaultUILanguage;
    static CACHE: OnceLock<bool> = OnceLock::new();
    *CACHE.get_or_init(|| {
        // LANGID 低 10 位是主语言 id，0x04 = 中文。
        (unsafe { GetUserDefaultUILanguage() } & 0x3ff) == 0x04
    })
}

#[cfg(not(windows))]
fn system_is_chinese() -> bool {
    true
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dictionaries_are_aligned() {
        assert_eq!(ZH.len(), EN.len());
        assert_eq!(ZH[79], "通用");
        assert_eq!(EN[79], "General");
        assert_eq!(ZH[85], "显示语言");
        assert_eq!(EN[85], "Display language");
    }

    #[test]
    fn text_translates_and_falls_back() {
        assert_eq!(text("en", "通用").as_str(), "General");
        assert_eq!(text("zh-CN", "通用").as_str(), "通用");
        assert_eq!(text("en", "不在字典里").as_str(), "不在字典里");
    }
}
